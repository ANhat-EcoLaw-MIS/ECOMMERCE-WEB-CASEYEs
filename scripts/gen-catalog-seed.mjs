// Generates the catalog seed migration from the canonical catalog (decision Q1: the database is
// the source of truth; supabase/seed/catalog.json is the only place the catalog is edited).
//
//   node scripts/gen-catalog-seed.mjs            → writes supabase/migrations/20261120090200_seed_catalog_v2.sql
//   node scripts/gen-catalog-seed.mjs --check    → exits 1 if the committed migration is out of date
//
// The generated SQL is idempotent (upserts by slug / sku_code), never deletes, and only
// deactivates the legacy rows the new catalog replaces.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'supabase', 'seed', 'catalog.json');
const OUT = join(ROOT, 'supabase', 'migrations', '20261120090200_seed_catalog_v2.sql');

/** Price of a custom (studio) case: flat, from phone_models.custom_price (Spec FR-DES-33). */
const CUSTOM_PRICE = 250000;
/** Flat price of a LIMITED / collab artwork on every device (pricelist GĐ-11). */
const LIMITED_PRICE = 239000;
/** Rows the new catalog replaces (kept for old orders, hidden from the shop). */
const LEGACY_ACCESSORIES = ['accessory-magsafe', 'accessory-airpods', 'accessory-strap'];

const catalog = JSON.parse(readFileSync(SRC, 'utf8'));

const q = (v) => (v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => (xs?.length ? `array[${xs.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const bool = (b) => (b ? 'true' : 'false');
const rows = (list) => list.map((r) => `  (${r.join(', ')})`).join(',\n');

const models = catalog.phoneModels;
const skus = models.flatMap((m) => m.skus.map((s) => ({ ...s, model: m })));

const sql = `-- P0-3 · Catalog seed v2 — GENERATED by scripts/gen-catalog-seed.mjs from supabase/seed/catalog.json.
-- Do not edit by hand: change catalog.json and run the script again.
-- ${catalog.designs.length} artworks × ${skus.length} phone-model SKUs, ${catalog.accessories.length} accessories, ${models.length} studio phone models.
-- Fixes Spec B5 (shop slugs, iphone-15-pro-max / xiaomi-14-ultra variants missing) and the data side of B4
-- (accessory ids). Idempotent; never deletes. The legacy rows it replaces are only deactivated
-- (order_items still point at them).
-- Rollback: supabase/rollbacks/20261120090200_seed_catalog_v2.down.sql

-- ---------------------------------------------------------------- phone models (Design Studio)
insert into public.phone_models (brand, name, slug, custom_price, has_3d_model, model_3d_url) values
${rows(models.map((m) => [q(m.brand), q(m.name), q(m.slug), CUSTOM_PRICE, bool(m.has3dModel), q(m.model3dUrl)]))}
on conflict (slug) do update
  set has_3d_model = excluded.has_3d_model,
      model_3d_url = excluded.model_3d_url,
      is_active    = true;

-- Phone models outside the catalog are not sold (Shop, Design Studio and onboarding offer the same list).
-- Kept, not deleted: old designs and orders still reference them.
update public.phone_models set is_active = false
where is_active and slug not in (${models.map((m) => q(m.slug)).join(', ')});

-- ---------------------------------------------------------------- one blank per SKU (stock = studio stockQty)
insert into public.inventory_items (kind, name, phone_model_id, quantity_on_hand, sku_code, case_type, color_name, color_hex)
select 'blank', 'Phôi SKU ' || m.name || ' · ' || s.color_name, m.id, s.qty, s.sku, s.case_type, s.color_name, s.color_hex
from (values
${rows(skus.map((s) => [q(s.model.slug), q(s.skuId), q(s.caseType), q(s.colorName), q(s.colorHex), s.stockQty]))}
) s (model_slug, sku, case_type, color_name, color_hex, qty)
join public.phone_models m on m.slug = s.model_slug
on conflict (sku_code) do update
  set case_type = excluded.case_type, color_name = excluded.color_name, color_hex = excluded.color_hex;

-- ---------------------------------------------------------------- artworks (ready-made cases)
insert into public.products (slug, name, description, product_type, image_url, collection, styles, tags, badge, caption, finish, premium, art_url) values
${rows(catalog.designs.map((d) => [q(d.id), q(d.name), q(d.description ?? ''), `'case'`, q(d.art ?? `/products/${d.id}.webp`), q(d.collection), arr(d.style ? [d.style] : []), arr(d.tags), q(d.badge), q(d.caption), q(d.finish), d.premium ?? 0, q(d.art)]))}
on conflict (slug) do update
  set name        = excluded.name,
      description = excluded.description,
      image_url   = coalesce(public.products.image_url, excluded.image_url),
      collection  = excluded.collection,
      styles      = excluded.styles,
      tags        = excluded.tags,
      badge       = excluded.badge,
      caption     = excluded.caption,
      finish      = excluded.finish,
      premium     = excluded.premium,
      art_url     = excluded.art_url,
      is_active   = true;

-- Every artwork on every available SKU: price = SKU price + artwork premium, or the flat limited price (same as the Shop UI).
-- A sold-out artwork keeps its variants but they are inactive.
with sku (sku, price, available) as (values
${rows(skus.map((s) => [q(s.skuId), s.price, bool(s.isAvailable)]))}
), art (slug, active) as (values
${rows(catalog.designs.map((d) => [q(d.id), bool(!d.soldOut)]))}
)
insert into public.product_variants (product_id, name, phone_model_id, inventory_item_id, price, color_sku, is_active)
select p.id, m.name || ' · ' || b.color_name, m.id, b.id, case when p.badge = 'LIMITED' then ${LIMITED_PRICE} else sku.price + p.premium end, b.sku_code, art.active and sku.available
from art
join public.products p on p.slug = art.slug
cross join sku
join public.inventory_items b on b.kind = 'blank' and b.sku_code = sku.sku
join public.phone_models m on m.id = b.phone_model_id
on conflict (product_id, coalesce(phone_model_id::text, ''), coalesce(color_sku, '')) do update
  set name = excluded.name, inventory_item_id = excluded.inventory_item_id, price = excluded.price, is_active = excluded.is_active;

-- Legacy per-model variants of the 8 original artworks (no SKU, own stock) are replaced by the SKU variants.
update public.product_variants v set is_active = false
from public.products p
where p.id = v.product_id and p.product_type = 'case' and v.color_sku is null and v.is_active;

-- ---------------------------------------------------------------- accessories (sold as-is, IN_STOCK)
insert into public.products (slug, name, description, product_type, image_url, category, badge) values
${rows(catalog.accessories.map((a) => [q(a.id), q(a.name), q(a.description ?? ''), `'accessory'`, q(a.image), q(a.category), q(a.badge)]))}
on conflict (slug) do update
  set name = excluded.name, description = excluded.description, image_url = excluded.image_url,
      category = excluded.category, badge = excluded.badge, is_active = true;

insert into public.inventory_items (kind, name, phone_model_id, quantity_on_hand, sku_code)
select 'trade_good', 'Kho ' || a.name, null, a.qty, a.slug
from (values
${rows(catalog.accessories.map((a) => [q(a.id), q(a.name), a.stock]))}
) a (slug, name, qty)
on conflict (sku_code) do nothing;

insert into public.product_variants (product_id, name, phone_model_id, inventory_item_id, price, color_sku, is_active)
select p.id, null, null, i.id, a.price, null, true
from (values
${rows(catalog.accessories.map((a) => [q(a.id), a.price]))}
) a (slug, price)
join public.products p on p.slug = a.slug
join public.inventory_items i on i.kind = 'trade_good' and i.sku_code = a.slug
on conflict (product_id, coalesce(phone_model_id::text, ''), coalesce(color_sku, '')) do update
  set inventory_item_id = excluded.inventory_item_id, price = excluded.price, is_active = true;

-- The three seed v1 accessories are not sold any more.
update public.products set is_active = false
where slug in (${LEGACY_ACCESSORIES.map(q).join(', ')});
`;

/** Slugs seeded by 20261114100600_seed_catalog.sql (v1); everything else in catalog.json is new in v2. */
const V1_SLUGS = ['lilac-dream', 'midnight-eyes', 'bloom-club', 'purple-orbit', 'little-love', 'noir-muse', 'cloud-nine', 'mono-heart',
  'accessory-magsafe', 'accessory-airpods', 'accessory-strap', 'gift-hologram'];
const newSlugs = [...catalog.designs, ...catalog.accessories].map((x) => x.id).filter((s) => !V1_SLUGS.includes(s));
/** Phone models seeded by v1; the ones outside catalog.json are deactivated by v2. */
const V1_MODELS = ['iphone-16-pro-max', 'iphone-16-pro', 'iphone-16', 'iphone-15-pro-max', 'iphone-15-pro', 'iphone-15',
  'iphone-14', 'galaxy-s24-ultra', 'galaxy-s24', 'galaxy-s23', 'xiaomi-14-ultra'];
const retiredModels = V1_MODELS.filter((s) => !models.some((m) => m.slug === s));

const down = `-- Rollback P0-3 — GENERATED by scripts/gen-catalog-seed.mjs (do not edit by hand).
-- Removes the rows seed v2 created and re-enables the seed v1 rows it replaced.
-- Like the M7 rollback, it fails (FK) if an order already uses a seed v2 variant.

update public.products set is_active = true
where slug in (${LEGACY_ACCESSORIES.map(q).join(', ')});
update public.product_variants v set is_active = true
from public.products p
where p.id = v.product_id and p.product_type = 'case' and v.color_sku is null;

-- Variants that use a per-SKU blank or a seed v2 accessory stock item.
delete from public.product_variants v
using public.inventory_items i
where i.id = v.inventory_item_id and i.sku_code is not null;

-- Products that only exist since seed v2.
delete from public.products where slug in (
${newSlugs.map((s) => `  ${q(s)}`).join(',\n')}
);

delete from public.inventory_items where sku_code is not null;
-- Phone models: seed v2 only updated existing rows (all studio models were already in seed v1);
-- the 3D columns go away with the P0-2 rollback. Re-enable the seed v1 models v2 retired.
${retiredModels.length ? `update public.phone_models set is_active = true where slug in (${retiredModels.map(q).join(', ')});` : ''}
`;
const DOWN = join(ROOT, 'supabase', 'rollbacks', '20261120090200_seed_catalog_v2.down.sql');

if (process.argv.includes('--check')) {
  const stale = [[OUT, sql], [DOWN, down]].filter(([f, text]) => readFileSync(f, 'utf8') !== text);
  if (stale.length) {
    console.error(`out of date: ${stale.map(([f]) => f).join(', ')} — run node scripts/gen-catalog-seed.mjs`);
    process.exit(1);
  }
  console.log('catalog seed is up to date');
} else {
  writeFileSync(OUT, sql);
  writeFileSync(DOWN, down);
  console.log(`wrote ${OUT}\nwrote ${DOWN}`);
}
